export const componentDefs: Map<ComponentTypeId, ComponentDef> = new Map(defs.map((d) => [d.type, d]));

export function defOf(type: ComponentTypeId): ComponentDef {
  const d = componentDefs.get(type);
  if (!d) throw new Error(`unknown component type ${type}`);
  return d;
}
